// node --experimental-vm-modules tests/turn_timer.test.mjs
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
let tick,interval,cleared;
const context=vm.createContext({setInterval(fn,ms){tick=fn;interval=ms;return 9;},clearInterval(id){cleared=id;}});
const mod=new vm.SourceTextModule(await readFile(new URL('../src/main/resources/static/js/turn-timer.js',import.meta.url),'utf8'),{context});
await mod.link(()=>{});await mod.evaluate();
const {turnSecondsLeft,turnTimerText,turnTimerMarkup,mountTurnTimers}=mod.namespace;
const fin=1_000_000;
assert.equal(turnSecondsLeft(fin,fin-60_000),60);
assert.equal(turnSecondsLeft(fin,fin-58_001),59,'Redondea hacia arriba');
assert.equal(turnSecondsLeft(fin,fin+5_000),0,'Nunca negativo');
assert.equal(turnSecondsLeft(fin,fin-60_900),60,'Nunca supera el límite del servidor');
assert.equal(turnSecondsLeft(null,fin),null);
assert.equal(turnSecondsLeft('x',fin),null);
assert.equal(turnTimerText(42),'⏳ 42 s');
assert.equal(turnTimerText(0),'⏳ Pasando turno…');
assert.equal(turnTimerMarkup(null,fin),'','Sin turno pendiente no hay cuenta atrás');
assert.match(turnTimerMarkup(fin,fin-30_000),/class="turn-timer" data-turn-end="1000000" aria-hidden="true">⏳ 30 s</);
assert.match(turnTimerMarkup(fin,fin-9_000),/turn-timer urgent/);
const classes=new Set();
const node={textContent:'',getAttribute:()=>String(fin),classList:{toggle(name,on){on?classes.add(name):classes.delete(name);}}};
let now=fin-15_000;
const timers=mountTurnTimers({querySelectorAll:()=>[node]},()=>now);
assert.equal(interval,250);assert.equal(node.textContent,'⏳ 15 s');assert.equal(classes.has('urgent'),false);
now=fin-10_000;tick();assert.equal(node.textContent,'⏳ 10 s');assert.equal(classes.has('urgent'),true);
now=fin;timers.tick();assert.equal(node.textContent,'⏳ Pasando turno…');
timers.destroy();assert.equal(cleared,9);
console.log('Temporizador de turno: segundos, urgencia, marca y reloj del servidor PASS');
