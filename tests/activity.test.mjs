// node --experimental-vm-modules tests/activity.test.mjs
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const context=vm.createContext({document:{getElementById:()=>({}),addEventListener(){}},window:{addEventListener(){}}});
const mod=new vm.SourceTextModule(await readFile(new URL('../src/main/resources/static/js/feedback.js',import.meta.url),'utf8'),{context});
await mod.link(()=>new vm.SourceTextModule('export const img=()=>"", esc=String, update=()=>{};', {context}));
await mod.evaluate();
const {currentActivity}=mod.namespace;
const base={yo:'Fali',actual:'Jefe',fase:'SELECCION_ROLES',ganadores:[],ronda:1,eventos:[{texto:'SECRETO'}]};
assert.match(currentActivity(base).title,/Jefe está eligiendo personaje/);
assert.equal(currentActivity({...base,yo:'Jefe'}).title,'Elige tu personaje');
assert.match(currentActivity({...base,fase:'TURNO_JUGADOR'}).title,/Jefe está jugando/);
assert(!JSON.stringify(currentActivity(base)).includes('SECRETO'));
assert.match(currentActivity({...base,yo:'Jefe',fase:'TURNO_JUGADOR',accionesRestantes:1}).detail,/1 acción disponible/);
assert.match(currentActivity({...base,yo:'Jefe',fase:'TURNO_JUGADOR',accionesRestantes:0}).detail,/Sin acciones base/);
assert.match(currentActivity({...base,yo:'Jefe',fase:'TURNO_JUGADOR',habilidadPendiente:true}).detail,/en privado/);
assert.match(currentActivity({...base,fase:'FIN_RONDA'}).detail,/siguiente ronda comenzará en unos segundos/);
assert.match(currentActivity({...base,fase:'FIN_PARTIDA',ganadores:['Fali']}).detail,/Victoria: Fali/);
console.log('9 comprobaciones de estado actual superadas');
